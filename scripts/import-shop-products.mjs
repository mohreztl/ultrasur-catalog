// One-off importer: builds src/importedProducts.ts from a folder of shop product images.
// Each subfolder is one product; the primary image filename is the product title.
// Usage: node scripts/import-shop-products.mjs "<source-folder>"
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const SOURCE =
  process.argv[2] ||
  String.raw`C:\Users\MoHreZ\Downloads\فایل تمامی محصولات بارگزاری شده - Copy\فایل تمامی محصولات بارگزاری شده - Copy`;

if (!fs.existsSync(SOURCE)) {
  console.error(`Source folder not found: ${SOURCE}`);
  process.exit(1);
}

const OUT_TS = path.join(repoRoot, "src", "importedProducts.ts");
const OUT_IMG_DIR = path.join(repoRoot, "public", "images", "imported");

// Category rules evaluated top to bottom against the Persian product title.
const CATEGORY_RULES = [
  [/پاور\s*بانک/, "powerbank"],
  [/ساعت/, "smartwatch"],
  [/فندکی/, "car-charger"],
  [/گردنی/, "neckband"],
  [/ایرپاد|بی\s*سیم|بلوتوث/i, "airpods"],
  [/هندزفری/, "wired-earphone"],
  [/هولدر|نگهدارنده/, "holder"],
  [/\bAUX\b|ايوایکس|ایوایکس|آیوایکس/i, "aux-cable"],
  [/کابل/, "cables"],
  [/اسپیکر|هدفون/, "speaker-acc"],
  [/شارژ/, "charger"],
  [/تبدیل|مبدل/, "cables"],
];

// Product titles may mix Arabic/Persian letter variants (ك/ک, ي/ی); normalize first.
const normalizeFa = (s) =>
  s.replace(/ك/g, "ک").replace(/ي/g, "ی").replace(/[ةۀ]/g, "ه");

const classify = (title) => {
  for (const [re, id] of CATEGORY_RULES) {
    if (re.test(title)) return id;
  }
  return "other";
};

const sanitizeId = (name, index) => {
  const s = name
    .replace(/[^A-Za-z0-9_-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-+|-+$/g, "");
  return s || `x-${index}`;
};

const titleFromFilename = (folderName, fileName) => {
  const base = fileName.replace(/\.[^.]+$/, "");
  if (/^IMG_/i.test(base)) return folderName; // camera shots carry no product name
  return normalizeFa(
    base
      .replace(/\s+\d{1,2}$/, "") // trailing image index like " 1"
      .replace(/\s{2,}/g, " ")
      .trim(),
  );
};

fs.rmSync(OUT_IMG_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_IMG_DIR, { recursive: true });

const entries = fs
  .readdirSync(SOURCE, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .sort((a, b) => a.name.localeCompare(b.name));

const products = [];
const IMG_EXT = [".png", ".webp", ".jpg", ".jpeg"];

for (const [idx, dir] of entries.entries()) {
  const dirPath = path.join(SOURCE, dir.name);
  const files = fs
    .readdirSync(dirPath, { withFileTypes: true })
    .filter(
      (f) => f.isFile() && IMG_EXT.includes(path.extname(f.name).toLowerCase()),
    )
    .map((f) => f.name);

  if (files.length === 0) {
    console.warn(`skip (no image): ${dir.name}`);
    continue;
  }

  // Prefer the " 1" variant, then png over other formats, then first alphabetically.
  const primary =
    files.find((f) => /\s1\.[^.]+$/i.test(f)) ??
    files.find((f) => f.toLowerCase().endsWith(".png")) ??
    files.sort()[0];

  const id = `imp-${sanitizeId(dir.name, idx)}`;
  const ext = path.extname(primary).toLowerCase();
  const imgName = `${id}${ext}`;
  fs.copyFileSync(path.join(dirPath, primary), path.join(OUT_IMG_DIR, imgName));

  const title = titleFromFilename(dir.name, primary);
  const category = classify(title);

  products.push({
    id,
    category,
    title,
    brand: "",
    capacity: "",
    price: 0,
    badge: "",
    image: `images/imported/${imgName}`,
    specs: [],
  });
}

const serialize = (p) => `  {
    id: ${JSON.stringify(p.id)},
    category: ${JSON.stringify(p.category)},
    title: ${JSON.stringify(p.title)},
    brand: "",
    capacity: "",
    price: 0,
    badge: "",
    image: ${JSON.stringify(p.image)},
    specs: [],
  },`;

const ts = `// AUTO-GENERATED by scripts/import-shop-products.mjs — do not edit by hand.
// Shop catalog import: one product per source folder, title from the image filename.
import type { Product } from "./App";

export const IMPORTED_PRODUCTS: Product[] = [
${products.map(serialize).join("\n")}
];
`;

fs.writeFileSync(OUT_TS, ts, "utf8");

const byCategory = {};
for (const p of products)
  byCategory[p.category] = (byCategory[p.category] || 0) + 1;
console.log(`imported ${products.length} products -> src/importedProducts.ts`);
console.log(byCategory);
